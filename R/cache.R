#' Construct path to cached result for the calling function
#'
#' @param n_frames_up Default is 1, which is to say: a path is constructed using
#'   the name and the arguments of the function calling
#'   `construct_cache_file_path()`. If `n_frames_up` = 2, a path is constructed
#'   using the name and the arguments of the function calling the function
#'   calling `construct_cache_file_path()`,.
#'
#' @returns A file path to a .rds file in the /derived subdirectory of the
#'   directory in which are stored the eHARS data currently being used within
#'   the R session. The file ame is constructed as `<function name>__<function
#'   argument names and values separated by '_'/'__'>`
#'
#' @examples
#' test_fun <- function(x = 1, y = 2, z = 3){construct_cache_file_path()}
#' test_fun()
#' rm(test_fun)
#'
construct_cache_file_path <- function(n_frames_up = 1) {
  fun_name <- sys.call(-1 * n_frames_up)[[1]]

  # Capture the calling function's formals
  fun_formals <- formals(sys.function(-1 * n_frames_up))

  # Retrieve caller's argument values from caller's environment
  fun_args <- mget(
    names(fun_formals),
    envir = parent.frame(n = n_frames_up),
    inherits = FALSE
  )

  # Drop selected arguments
  fun_args <- fun_args[setdiff(names(fun_args), "cache")]

  # Construct file name from calling function name + args
  cache_fn <- paste0(
    fun_name,
    "__",
    paste(names(fun_args), fun_args, sep = "_", collapse = "__")
  ) |>
    stringr::str_replace_all('[\\\\/:*?"<>|]', "_")

  cache_file_path <- file.path(
    ehars_root_dir(),
    "Archive",
    getOption("kcHARS.ehars_dt"),
    "derived",
    paste0(cache_fn, ".rds")
  )

  return(cache_file_path)
}

#' Write/overwrite file in the cache
#'
#' @param x the object to write/overwrite in the cache, using the file path
#'   generated by construct_cache_file_path()
#' @param cache One of "use", "ignore", "overwrite". If `cache` = 'use', `x` is
#'   saved to the cache so long as it doesn't already exist there. If `cache` =
#'   'overwrite', `x` is saved to the cache, overwriting an existing object if
#'   one exists. If `cache` = 'ignore', nothing is done.
#'
#' @returns Saves an .rds file to the cache depending
#'
#' @examples
#' df <- data.frame(x = 1:10)
#' temp_fun <- function(x = 1, y = 2, z = 3, cache){product = x*y*z; write_to_cache(x = product, cache = cache)}
#' temp_fun(cache = "use")
#' temp_fun(cache = "ignore")
#' temp_fun(cache = "overwrite")
#' rm(test_fun)
write_to_cache <- function(
  x,
  cache
) {
  stopifnot(cache %in% c("use", "ignore", "overwrite"))

  cache_file_path <- construct_cache_file_path(n_frames_up = 2)

  if (cache == 'use') {
    # only save in cache if file doesn't already exist
    if (!file.exists(cache_file_path)) {
      # create /derived subdirectory if it doesn't yet exist
      if (!dir.exists(dirname(cache_file_path))) {
        dir.create(dirname(cache_file_path))
      }
      saveRDS(object = x, file = cache_file_path)
    }
  } else if (cache == 'overwrite') {
    saveRDS(object = x, file = cache_file_path)
  }
}
