#' Compile a list of documented dates of HIV care (labs and optionally
#' care_nolab and/or ARV use)
#'
#' @param incl_care_nolab Logical value specifying whether to include care_nolab
#'   dates
#' @param incl_ARV_dts Logical value specifying whether to include documented
#'   dates of ARV use
#' @param excl_care_before_dx Logical value specifying whether to drop care
#'   dates earlier than the earliest date of HIV diagnosis
#' @param care_dt..to Two-digit (zero-padded, as needed) character value
#'   specifying the day to impute for dates of care, where missing. Defaults to
#'   '15'
#' @param care_dt....to Four-digit (zero-padded, as needed) character value
#'   specifying the month+day to impute for dates of care, where missing.
#'   Defaults to '0630'
#' @param cache Whether to use or overwrite cached results. Must be one of 'use'
#'   (the default), 'overwrite', or 'ignore'. If cache = 'use' (the default) and
#'   a dataset was generated by a previous call to this function *using the same
#'   parameters* and the same eHARS data and was cached, the cached dataset is
#'   returned, otherwise a dataset is derived and cached. If cache =
#'   'overwrite', a dataset is (re-)derived and (re-)cached, overwriting any
#'   existing analogous dataset in the cache. If cache = 'ignore', a dataset is
#'   re-derived but not (re-)cached.
#'
#' @returns A data.frame unique by stateno + care_dt_char (i.e., character value
#'   stored in lab.sample_dt / care_nolab_dt from the observation dataset /
#'   arv_prophylaxis.drug_start_dt / arv_prophylaxis.drug_last_use_dt). Contains
#'   variables care_dt (Date), care_type (1+ of: 'VL', 'CD4 cnt', 'CD4 pct',
#'   'care_nolab (doc)', 'care_nolab (self-rpt)', 'drug_start_dt',
#'   'drug_last_use_dt'), first_enter_dt (Date; earliest enter_dt for any
#'   document with this stateno + care_dt_char), document_uid (for documents
#'   with this stateno + care_dt_char, by care_type), and facility (for *lab*
#'   documents with this stateno + care_dt_char).
#'
#'   #' @details The cached dataset is stored in the "/Derived" subdirectory of
#'   the date-specific folder containing the eHARS datasets. If no such
#'   directory exists when this function is called, it creates it.
#' @export
#' @importFrom data.table ":=" set fcase
#'
#' @examples
#' care_dts <- get_care_dts()

get_care_dts <- function(
  incl_care_nolab = TRUE,
  incl_ARV_dts = TRUE,
  excl_care_before_dx = TRUE,
  care_dt..to = "15",
  care_dt....to = "0630",
  cache = "use"
) {
  stopifnot(is.logical(incl_care_nolab))
  stopifnot(is.logical(incl_ARV_dts))
  stopifnot(is.logical(excl_care_before_dx))

  checkmate::assert_character(care_dt..to, pattern = "^[0-9]{2}$")
  checkmate::assert_numeric(as.integer(care_dt..to), lower = 1, upper = 31)
  checkmate::assert_character(care_dt....to, pattern = "^[0-9]{4}$")
  checkmate::assert_numeric(
    stringr::str_sub(care_dt....to, 1, 2) |> as.integer(),
    lower = 1,
    upper = 12
  )
  checkmate::assert_numeric(
    stringr::str_sub(care_dt....to, 3, 4) |> as.integer(),
    lower = 1,
    upper = 31
  )

  stopifnot(cache %in% c("use", "ignore", "overwrite"))

  if (cache == "use") {
    # check if a cached dataset generated by a previous run using the same
    # parameters already exists and, if so, read it in and return it
    cache_file_path <- construct_cache_file_path() # NOTE: cannot simpl
    if (file.exists(cache_file_path)) {
      return(readRDS(cache_file_path))
    }
  }

  # get dates of CD4s and VLs ----

  VLs_CD4s <- read_ehars_doc(
    "lab",
    col_select = c(
      "document_uid",
      "sample_dt",
      "facility_uid",
      "lab_test_cd"
    )
  ) |>
    dplyr::filter(
      lab_test_cd %in%
        c(
          'EC-060', # HIV-1 RNA/DNA NAAT (Quantitative)
          'EC-061', # HIV-2 RNA/DNA NAAT (Quantitative)
          'EC-014', # HIV-1 RNA/DNA NAAT (Quantitative viral load)'
          'EC-015', # HIV-2 RNA/DNA NAAT (Quantitative viral load)'
          'L-010', # Viral Load-Other-Legacy'
          'L-011', # Viral Load-Unspecified-Legacy'
          'EC-016', # CD4 T-lymphocytes'
          'EC-017' # CD4 Percent'
        )
    ) |>
    dplyr::left_join(
      read_ehars_doc(
        "document",
        col_select = c("document_uid", "ehars_uid", "enter_dt")
      ),
      by = "document_uid"
    ) |>
    dplyr::left_join(
      read_ehars_person(
        col_select = c("stateno", "ehars_uid")
      ),
      by = "ehars_uid"
    ) |>
    dplyr::left_join(
      read_ehars_doc("facility_code", col_select = c("facility_uid", "name1")),
      by = "facility_uid"
    ) |>
    dplyr::rename(facility = name1) |>
    dplyr::select(-facility_uid, -ehars_uid) |>
    dplyr::distinct()

  care_dts <- VLs_CD4s |>
    dtplyr::lazy_dt() |>
    # NOTE: the above enables the dtplyr package to automatically translate
    # dplyr pipelines into highly optimized data.table code behind the scenes
    dplyr::mutate(
      care_type = dplyr::case_when(
        lab_test_cd == 'EC-016' ~ 'CD4 cnt',
        lab_test_cd == 'EC-017' ~ 'CD4 pct',
        TRUE ~ 'VL'
      ),
      care_dt_char = sample_dt,
      care_dt = ehars_dt.as.Date(
        sample_dt,
        ..to = care_dt..to,
        ....to = care_dt....to
      ),
      enter_dt = ehars_dt.as.Date(enter_dt)
    ) |>
    dplyr::summarize(
      .by = c("stateno", "care_dt_char", "care_dt", "care_type"),
      facility = facility |> na.omit() |> unique() |> paste(collapse = ", "),
      first_enter_dt = min(enter_dt, na.rm = TRUE),
      document_uid = document_uid |> unique() |> paste(collapse = ", ")
    ) |>
    dplyr::as_tibble()

  # get care_nolab dates ----
  if (incl_care_nolab) {
    care_nolab_dts0 <- read_ehars_doc(
      "OBSERVATION",
      col_select = c(document_uid, obs_uid, obs_value)
    ) |>
      dplyr::filter(
        obs_uid == '240' # care_nolab_dt
      ) |>
      dplyr::rename(care_nolab_dt = obs_value) |>
      dplyr::left_join(
        read_ehars_doc(
          "OBSERVATION",
          col_select = c(document_uid, obs_uid, obs_value)
        ) |>
          dplyr::filter(
            obs_uid == '239' # care_nolab
          ) |>
          dplyr::rename(care_nolab = obs_value),
        by = "document_uid"
      ) |>
      dplyr::left_join(
        read_ehars_doc(
          "document",
          col_select = c("document_uid", "ehars_uid", "enter_dt")
        ),
        by = "document_uid"
      ) |>
      dplyr::left_join(
        read_ehars_person(col_select = c("stateno", "ehars_uid")),
        by = "ehars_uid"
      )

    care_nolab_dts <- care_nolab_dts0 |>
      dtplyr::lazy_dt() |>
      dplyr::mutate(
        care_dt_char = care_nolab_dt,
        care_dt = ehars_dt.as.Date(
          care_nolab_dt,
          ..to = care_dt..to,
          ....to = care_dt....to
        ),
        enter_dt = ehars_dt.as.Date(enter_dt)
      ) |>
      dplyr::summarise(
        .by = c("stateno", "care_dt_char", "care_dt"),
        care_type = min(care_nolab, na.rm = TRUE) |>
          dplyr::recode_values(
            "1" ~ "care_nolab (doc)",
            "2" ~ "care_nolab (self-rpt)"
          ),
        facility = "",
        first_enter_dt = min(enter_dt, na.rm = TRUE),
        document_uid = document_uid |>
          na.omit() |>
          unique() |>
          paste(collapse = ', ')
      ) |>
      dplyr::as_tibble()

    care_dts <- rbind(
      care_dts,
      care_nolab_dts
    )
  }
  # get dates of documented ARV use ----
  if (incl_ARV_dts) {
    ARV_dts0 <- read_ehars_doc(
      "arv_prophylaxis",
      col_select = c(document_uid, drug_start_dt, drug_last_use_dt)
    ) |>
      dplyr::left_join(
        read_ehars_doc(
          "document",
          col_select = c("document_uid", "ehars_uid", "enter_dt")
        ),
        by = "document_uid"
      ) |>
      dplyr::left_join(
        read_ehars_person(col_select = c("stateno", "ehars_uid")),
        by = "ehars_uid"
      )

    ARV_dts <- ARV_dts0 |>
      dtplyr::lazy_dt() |>
      # convert empty strings to NA so dropped when pivot longer
      dplyr::mutate(dplyr::across(
        .cols = c("drug_start_dt", "drug_last_use_dt"),
        .fns = function(x) {
          x |> dplyr::replace_values("" ~ NA)
        }
      )) |>
      tidyr::pivot_longer(
        cols = c("drug_start_dt", "drug_last_use_dt"),
        values_to = "care_dt_char",
        names_to = "care_type",
        values_drop_na = TRUE
      ) |>
      dplyr::mutate(
        care_dt = ehars_dt.as.Date(
          care_dt_char,
          ..to = care_dt..to,
          ....to = care_dt....to
        ),
        enter_dt = ehars_dt.as.Date(enter_dt)
      ) |>
      dplyr::summarise(
        .by = c("stateno", "care_dt_char", "care_dt"),
        care_type = min(care_type, na.rm = TRUE), # drug_last_use_dt < drug_start_dt
        facility = "",
        first_enter_dt = min(enter_dt, na.rm = TRUE),
        document_uid = document_uid |>
          na.omit() |>
          unique() |>
          paste(collapse = ", ")
      ) |>
      dplyr::as_tibble()

    care_dts <- rbind(
      care_dts,
      ARV_dts
    )
  }

  # excl care before dx ----
  if (excl_care_before_dx) {
    care_dts <- care_dts |>
      dplyr::left_join(
        read_ehars_person(col_select = c(stateno, hiv_aids_dx_dt)),
        by = "stateno"
      ) |>
      dplyr::mutate(hiv_aids_dx_dt = ehars_dt.as.Date(hiv_aids_dx_dt)) |>
      dplyr::filter_out(care_dt < hiv_aids_dx_dt)
  }

  # summarize by stateno + care_dt_char ----
  care_dts_final <- care_dts |>
    dtplyr::lazy_dt() |>
    dplyr::mutate(document_uid = paste0(care_type, ": ", document_uid)) |>
    dplyr::summarise(
      .by = c("stateno", "care_dt_char", "care_dt"),
      care_type = care_type |> na.omit() |> unique() |> paste(collapse = ', '),
      facility = facility |> na.omit() |> unique() |> paste(collapse = ', '),
      first_enter_dt = min(first_enter_dt, na.rm = TRUE),
      document_uid = document_uid |>
        na.omit() |>
        unique() |>
        paste(collapse = '; ')
    ) |>
    dplyr::as_tibble()

  Misc.SHH.f::assert_unique(
    df = care_dts_final,
    by = c("stateno", "care_dt_char")
  )

  write_to_cache(x = care_dts_final, cache = cache)

  return(care_dts_final)
}

